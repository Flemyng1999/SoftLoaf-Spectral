"""Red-fast CUBE blocks and mapped readback, without a full mesh or row list."""
from pathlib import Path
import numpy as np
from spectral_lut.reference import Cube


def grid_blocks(size,low,high,block=8192):
    for start in range(0,size**3,block):
        ids=np.arange(start,min(start+block,size**3));indices=np.column_stack((ids%size,(ids//size)%size,ids//(size*size)))
        yield start,low+indices*(high-low)/(size-1)


def header(stream,size,low,high,title,comments):
    safe=lambda v:' '.join(''.join(c if c.isprintable() else ' ' for c in str(v)).split())
    stream.write('# Generated by SoftLoaf Spectral\nTITLE "'+safe(title).replace('"',"'").replace('\\','/')+'"\n')
    for value in comments:stream.write('# '+safe(value)+'\n')
    stream.write(f'LUT_3D_SIZE {size}\nDOMAIN_MIN '+' '.join(f'{v:.17g}' for v in low)+'\nDOMAIN_MAX '+' '.join(f'{v:.17g}' for v in high)+'\n')


def write_cube(path,size,low,high,render,title,comments,block=8192):
    mapped=Path(path).with_suffix('.nodes');values=np.memmap(mapped,mode='w+',shape=(size**3,3),dtype=np.float32)
    try:
        with Path(path).open('w',encoding='utf-8',newline='\n') as stream:
            header(stream,size,low,high,title,comments)
            for start,points in grid_blocks(size,low,high,block):
                output=np.asarray(render(points),dtype=np.float32)
                if output.shape!=points.shape or not np.isfinite(output).all():raise ValueError('Invalid LUT GPU output')
                values[start:start+len(output)]=output
                np.savetxt(stream,output,fmt='%.9g')
        values.flush()
    finally:values._mmap.close()
    return mapped


def read_cube(path,mapped_path,expected,block=8192,expected_low=None,expected_high=None):
    size=None;low=np.zeros(3);high=np.ones(3);pending=[];count=0;target=None;original=None
    try:
        with Path(path).open(encoding='utf-8') as stream:
            for line in stream:
                words=line.split('#',1)[0].split()
                if not words or words[0]=='TITLE':continue
                if words[0]=='LUT_3D_SIZE':
                    if size is not None:raise ValueError('Duplicate CUBE size')
                    size=int(words[1])
                    if Path(expected).stat().st_size!=size**3*3*4:raise ValueError('CUBE size differs from baked nodes')
                    if not 2<=size<=129:raise ValueError('Invalid CUBE size')
                    target=np.memmap(mapped_path,mode='w+',dtype=np.float32,shape=(size**3,3));original=np.memmap(expected,mode='r',dtype=np.float32,shape=(size**3,3));continue
                if words[0] in ('DOMAIN_MIN','DOMAIN_MAX'):
                    if len(words)!=4:raise ValueError('Invalid CUBE domain')
                    if words[0]=='DOMAIN_MIN':low=np.array(words[1:],dtype=float)
                    else:high=np.array(words[1:],dtype=float)
                    continue
                if target is None or len(words)!=3:raise ValueError('Invalid CUBE data')
                pending.append(words)
                if len(pending)==block:
                    count=_flush(pending,target,original,count);pending=[]
            if pending:count=_flush(pending,target,original,count)
        if size is None or count!=size**3 or not np.isfinite([low,high]).all() or np.any(high<=low) or (expected_low is not None and not np.array_equal(low,expected_low)) or (expected_high is not None and not np.array_equal(high,expected_high)):raise ValueError('Incomplete CUBE')
        target.flush();target._mmap.close();target=None
        table=np.memmap(mapped_path,mode='r',dtype=np.float32,shape=(size,size,size,3)).transpose(2,1,0,3)
        return Cube(table,low,high)
    finally:
        if target is not None:target._mmap.close()
        if original is not None:original._mmap.close()


def _flush(rows,target,original,count):
    values=np.asarray(rows,dtype=np.float32)
    if count+len(values)>len(target) or not np.isfinite(values).all() or not np.array_equal(values,original[count:count+len(values)]):raise ValueError('CUBE readback differs from baked GPU nodes')
    target[count:count+len(values)]=values
    return count+len(values)
