"""Numerical reference operations. Input units belong to the experiment recipe."""

from dataclasses import dataclass
from pathlib import Path

import numpy as np


def quadrature_widths(wavelengths):
    x = np.asarray(wavelengths, dtype=np.float64)
    if x.ndim != 1 or len(x) < 2 or not np.isfinite(x).all() or np.any(np.diff(x) <= 0):
        raise ValueError('Wavelengths must be finite and strictly increasing.')
    dx = np.diff(x)
    return np.r_[dx[0]/2, (dx[:-1]+dx[1:])/2, dx[-1]/2]


def acescct_encode(linear):
    x = np.asarray(linear, dtype=np.float64)
    out = 10.5402377416545*x + 0.0729055341958355
    return np.where(x > 0.0078125, (np.log2(np.maximum(x, np.finfo(float).tiny))+9.72)/17.52, out)


def acescct_decode(encoded):
    x = np.asarray(encoded, dtype=np.float64)
    return np.where(x > 0.155251141552511, np.exp2(x*17.52-9.72),
                    (x-0.0729055341958355)/10.5402377416545)


def density_transmittance(amounts, dyes):
    a, d = np.asarray(amounts, dtype=np.float64), np.asarray(dyes, dtype=np.float64)
    if np.any(a < 0) or np.any(d < 0) or not np.isfinite(a).all() or not np.isfinite(d).all():
        raise ValueError('Density components must be finite and nonnegative.')
    return np.power(10.0, -(a @ d.T))


def decreasing_projection(values):
    x = np.asarray(values, dtype=np.float64)
    blocks = []
    for value in x:
        blocks.append([float(value), 1])
        while len(blocks) > 1 and blocks[-2][0] < blocks[-1][0]:
            right, left = blocks.pop(), blocks.pop()
            count = left[1]+right[1]
            blocks.append([(left[0]*left[1]+right[0]*right[1])/count, count])
    return np.concatenate([np.full(count, mean) for mean, count in blocks])


def smooth_reconstruction_basis(kernel, regularization=1e-8):
    a = np.asarray(kernel, dtype=np.float64)
    n = len(a)
    diff = np.diff(np.eye(n), axis=0)
    penalty = diff.T @ diff + regularization*np.eye(n)
    system = np.block([[penalty, a], [a.T, np.zeros((3, 3))]])
    rhs = np.vstack([np.zeros((n, 3)), np.eye(3)])
    return np.linalg.solve(system, rhs)[:n].T


@dataclass
class Cube:
    table: np.ndarray
    domain_min: np.ndarray
    domain_max: np.ndarray

    def write(self, path, *, title='SoftLoaf Spectral', comments=()):
        n = self.table.shape[0]
        if self.table.shape != (n, n, n, 3) or n < 2 or not np.isfinite(self.table).all():
            raise ValueError('Expected a finite N by N by N RGB table.')
        if np.any(self.domain_max <= self.domain_min):
            raise ValueError('Invalid LUT domain.')
        def one_line(value):
            return ' '.join(''.join(c if c.isprintable() else ' ' for c in str(value)).split())
        with Path(path).open('w', encoding='utf-8', newline='\n') as f:
            f.write('# Generated by SoftLoaf Spectral\n')
            safe_title = one_line(title).replace('"', "'").replace('\\', '/')
            f.write(f'TITLE "{safe_title}"\n')
            for comment in comments:
                f.write('# ' + one_line(comment) + '\n')
            f.write(f'LUT_3D_SIZE {n}\n')
            f.write('DOMAIN_MIN ' + ' '.join(f'{v:.17g}' for v in self.domain_min) + '\n')
            f.write('DOMAIN_MAX ' + ' '.join(f'{v:.17g}' for v in self.domain_max) + '\n')
            # CUBE serializes red fastest, blue slowest.
            np.savetxt(f, self.table.transpose(2, 1, 0, 3).reshape(-1, 3), fmt='%.17g')

    @classmethod
    def read(cls, path):
        n, low, high, rows = None, np.zeros(3), np.ones(3), []
        for line in Path(path).read_text().splitlines():
            words = line.split('#', 1)[0].split()
            if not words or words[0] == 'TITLE':
                continue
            if words[0] == 'LUT_3D_SIZE':
                n = int(words[1])
            elif words[0] == 'DOMAIN_MIN':
                low = np.array(words[1:], dtype=np.float64)
            elif words[0] == 'DOMAIN_MAX':
                high = np.array(words[1:], dtype=np.float64)
            else:
                rows.append([float(v) for v in words])
        if n is None or len(rows) != n**3:
            raise ValueError('Incomplete 3D CUBE file.')
        table = np.array(rows).reshape(n, n, n, 3).transpose(2, 1, 0, 3)
        return cls(table, low, high)

    def apply(self, values, interpolation='tetrahedral'):
        if interpolation not in ('tetrahedral', 'trilinear'):
            raise ValueError('Expected tetrahedral or trilinear interpolation.')
        values = np.asarray(values, dtype=np.float64)
        shape = values.shape
        points = values.reshape(-1, 3)
        n = self.table.shape[0]
        positions = np.clip((points-self.domain_min)/(self.domain_max-self.domain_min), 0, 1)*(n-1)
        base = np.minimum(np.floor(positions).astype(int), n-2)
        fractions = positions-base
        if interpolation == 'trilinear':
            result = np.zeros_like(points)
            for corner in np.ndindex(2, 2, 2):
                offset = np.array(corner)
                weight = np.prod(np.where(offset, fractions, 1-fractions), axis=1)
                result += weight[:, None]*self.table[tuple((base+offset).T)]
            return result.reshape(shape)
        order = np.argsort(-fractions, axis=1, kind='stable')
        rank = np.arange(len(points))
        step1 = np.zeros_like(base)
        step1[rank, order[:, 0]] = 1
        step2 = np.ones_like(base)
        step2[rank, order[:, 2]] = 0
        c0 = self.table[tuple(base.T)].astype(np.float64, copy=False)
        c1 = self.table[tuple((base+step1).T)].astype(np.float64, copy=False)
        c2 = self.table[tuple((base+step2).T)].astype(np.float64, copy=False)
        c3 = self.table[tuple((base+1).T)].astype(np.float64, copy=False)
        f = np.take_along_axis(fractions, order, axis=1)
        result = c0 + f[:, :1]*(c1-c0) + f[:, 1:2]*(c2-c1) + f[:, 2:]*(c3-c2)
        return result.reshape(shape)
